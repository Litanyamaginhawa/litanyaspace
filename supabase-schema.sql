do $$
declare t text;
begin
  foreach t in array array[
    'profiles','posts','comments','post_reactions','bookmarks','blocks',
    'follows','reports','push_subscriptions','profile_views',
    'myday_stories','myday_replies','myday_story_views',
    'conversations','conversation_members','messages','message_reactions','notifications',
    'advice_posts','advice_replies',
    'game_rooms','game_room_players','game_room_events'
  ] loop
    execute format('drop policy if exists "litanya_open_%1$s" on public.%1$I', t);
    execute format(
      'create policy "litanya_open_%1$s" on public.%1$I for all to anon, authenticated using (true) with check (true)',
      t
    );
  end loop;
end $$;

