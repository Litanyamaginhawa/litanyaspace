-- 8) NOTIFICATION TRIGGERS
-- (the in-app bell gets its rows from these database triggers)
-- ============================================================

create or replace function public.litanya_actor_name(uid_text text)
returns text language sql stable as $$
  select coalesce(nullif((select username from public.profiles where id::text = uid_text), ''), 'Someone');
$$;

-- 8.1 reactions -> post owner
create or replace function public.litanya_notify_reaction()
returns trigger language plpgsql security definer set search_path = public as $$
declare owner_text text;
begin
  select user_id::text into owner_text from public.posts where id::text = new.post_id::text;
  if owner_text is not null and owner_text <> new.user_id::text and owner_text ~* '^[0-9a-f-]{36}$' then
    insert into public.notifications(user_id, type, title, body, post_id)
    values (owner_text::uuid, 'reaction', 'New reaction',
            public.litanya_actor_name(new.user_id::text) || ' reacted to your post.', new.post_id);
  end if;
  return new;
end $$;

-- 8.2 comments / replies -> post owner + parent comment author
create or replace function public.litanya_notify_comment()
returns trigger language plpgsql security definer set search_path = public as $$
declare owner_text text; parent_text text;
begin
  select user_id::text into owner_text from public.posts where id::text = new.post_id::text;
  if owner_text is not null and owner_text <> new.user_id::text and owner_text ~* '^[0-9a-f-]{36}$' then
    insert into public.notifications(user_id, type, title, body, post_id, comment_id)
    values (owner_text::uuid, 'comment', 'New comment',
            public.litanya_actor_name(new.user_id::text) || ' commented on your post.',
            new.post_id, new.id);
  end if;
  if new.parent_comment_id is not null then
    select user_id::text into parent_text from public.comments where id::text = new.parent_comment_id::text;
    if parent_text is not null and parent_text <> new.user_id::text and parent_text is distinct from owner_text
       and parent_text ~* '^[0-9a-f-]{36}$' then
      insert into public.notifications(user_id, type, title, body, post_id, comment_id)
      values (parent_text::uuid, 'comment_reply', 'New reply',
              public.litanya_actor_name(new.user_id::text) || ' replied to your comment.',
              new.post_id, new.id);
    end if;
  end if;
  return new;
end $$;

-- 8.3 direct/group messages -> all other members (Public Chat excluded)
create or replace function public.litanya_notify_message()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if exists (
    select 1 from public.conversations c
    where c.id::text = new.conversation_id::text and c.name = 'Public Chat'
  ) then
    return new;
  end if;
  insert into public.notifications(user_id, type, title, body, conversation_id, message_id)
  select cm.user_id::uuid, 'message', 'New message',
         public.litanya_actor_name(new.sender_id::text) || ' sent a message: ' || left(coalesce(new.content, ''), 80),
         new.conversation_id, new.id
  from public.conversation_members cm
  where cm.conversation_id::text = new.conversation_id::text
    and cm.user_id::text <> new.sender_id::text
    and cm.user_id::text ~* '^[0-9a-f-]{36}$';
  return new;
end $$;

-- 8.4 MyDay replies -> story owner
create or replace function public.litanya_notify_myday_reply()
returns trigger language plpgsql security definer set search_path = public as $$
declare owner_text text;
begin
  select user_id::text into owner_text from public.myday_stories where id::text = new.story_id::text;
  if owner_text is not null and owner_text <> new.sender_id::text and owner_text ~* '^[0-9a-f-]{36}$' then
    insert into public.notifications(user_id, type, title, body)
    values (owner_text::uuid, 'myday_reply', 'New MyDay reply',
            public.litanya_actor_name(new.sender_id::text) || ' replied to your MyDay.');
  end if;
  return new;
end $$;

